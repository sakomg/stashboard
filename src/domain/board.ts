export function pickName(taken: ReadonlySet<string>, random: () => number): string {
  const free = CHARACTERS.filter((name) => !taken.has(name));
  if (free.length > 0) return free[Math.floor(random() * free.length)]!;
  const base = CHARACTERS[Math.floor(random() * CHARACTERS.length)]!;
  let n = 2;
  while (taken.has(`${base} ${n}`)) n++;
  return `${base} ${n}`;
}
