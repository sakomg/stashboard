// Renders a QR code as an SVG string, for the authenticator link shown during setup.
import qrcode from 'qrcode-generator';

const QUIET_ZONE = 4;

export function qrSvg(text: string): string {
  const qr = qrcode(0, 'M');
  qr.addData(text);
  qr.make();
  const count = qr.getModuleCount();
  const size = count + QUIET_ZONE * 2;
  let path = '';
  for (let row = 0; row < count; row++) {
    for (let col = 0; col < count; col++) {
      if (qr.isDark(row, col)) path += `M${col + QUIET_ZONE} ${row + QUIET_ZONE}h1v1h-1z`;
    }
  }
  // Dark on light, whatever the page theme: phone cameras read inverted codes poorly.
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">` +
    `<rect width="${size}" height="${size}" fill="#ede8dc"/><path d="${path}" fill="#0b0f14"/></svg>`
  );
}
